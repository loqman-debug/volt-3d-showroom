export function getProductById(id: string): Product | undefined {
  return productsData.find((p) => p.id === id || p.slug === id);
}

export function getFeaturedProducts(): Product[] {
  return productsData.filter((p) => p.isFeatured);
}

export function getDealProducts(): Product[] {
  return productsData.filter((p) => p.isDeal || (p.discountPercentage && p.discountPercentage > 10));
}

export function getProductsByCategory(category: string): Product[] {
  if (category === 'all') return productsData;
  return productsData.filter((p) => p.category === category);
}

export function getRelatedProducts(productId: string, limit = 4): Product[] {
  const current = getProductById(productId);
  if (!current) return productsData.slice(0, limit);
  return productsData
    .filter((p) => p.id !== current.id && (p.category === current.category || p.brand === current.brand))
    .slice(0, limit);
}
